#!/usr/bin/env bash
# scripts/run-e2e-full-lab.sh
#
# End-to-end greenfield proof:
#   1. Purge and recreate the KVM lab
#   2. Converge multi-instance site (super DG + duper + fluff) at baseline 19.31
#   3. Install/patch dbhome_2 @ 19.31 for standalone DBs (no Restart switch)
#   4. Dual-home upgrade standalone DBs to 19.32 (prepare home2 → cutover →
#      rebuild home1 → cutover back)
#   5. Super DG: skip standby-first for OJVM+RU combo (apply combos together via
#      dual-home/downtime; SF only for fully SF-eligible media)
#   6. Warm Data Guard switchover cycle
#   7. Power-cycle and prove automatic Oracle/observer startup
#   8. Full pytest suite
#
# Usage:
#   scripts/run-e2e-full-lab.sh
#   SKIP_LAB_RECREATE=1 scripts/run-e2e-full-lab.sh   # reuse existing VMs
#   SKIP_TESTS=1 scripts/run-e2e-full-lab.sh
#   SKIP_SUPER_UPGRADE=0  # reserved; SF on combo is not the default path

set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "${REPO_DIR}"

LOG="${E2E_LOG:-/tmp/e2e-full-lab.log}"
exec > >(tee -a "${LOG}") 2>&1

echo "======== E2E START $(date -Is) log=${LOG} ========"

export ANSIBLE_LOCAL_TEMP="${ANSIBLE_LOCAL_TEMP:-/tmp/ansible-local}"
export ANSIBLE_SSH_CONTROL_PATH_DIR="${ANSIBLE_SSH_CONTROL_PATH_DIR:-/tmp/ansible-cp}"
export XDG_CACHE_HOME="${XDG_CACHE_HOME:-/tmp/ansible-cache}"
export LAB_ROOT_DISK_SIZE="${LAB_ROOT_DISK_SIZE:-250G}"
# System QEMU cannot traverse private $HOME; prefer the libvirt-readable stage.
if [ -z "${SOURCES_DIR:-}" ]; then
  if [ -d /var/lib/libvirt/ansible-oracle-sources ]; then
    export SOURCES_DIR=/var/lib/libvirt/ansible-oracle-sources
  else
    export SOURCES_DIR="${HOME}/sources/oracle"
  fi
fi

INV="${INVENTORY:-inventory/hosts.yml}"
SMOKE="inventory/examples/multi-instance-smoke.yml"
PB="${ANSIBLE_PLAYBOOK:-}"
if [ -z "${PB}" ]; then
  if [ -x "${REPO_DIR}/.venv/bin/ansible-playbook" ]; then
    PB="${REPO_DIR}/.venv/bin/ansible-playbook"
  else
    PB="$(command -v ansible-playbook)"
  fi
fi

# Baseline 19.31 media (inventory defaults)
BASE_DB_ZIP="/u01/stage/p39062931_190000_Linux-x86-64.zip"
BASE_DB_COMPONENT="39062931/39034528"
BASE_RU="19.31.0.0.260421"
BASE_PATCH_ID="39034528"

# Upgrade 19.32 media
UPG_DB_ZIP="/u01/stage/p39618649_190000_Linux-x86-64.zip"
UPG_DB_COMPONENT="39618649/39472050"

SKIP_LAB_RECREATE="${SKIP_LAB_RECREATE:-0}"
SKIP_TESTS="${SKIP_TESTS:-0}"
SKIP_SUPER_UPGRADE="${SKIP_SUPER_UPGRADE:-0}"

step() {
  echo
  echo "======== $(date -Is) $* ========"
}

fail() {
  echo "ERROR: $*" >&2
  exit 1
}

run_pb() {
  echo "+ ${PB} $*"
  "${PB}" "$@"
}

# Standalone-only vars for dual-home prepare (rejects DG instances).
write_standalone_vars() {
  local current_home="${1:-dbhome_1}"
  local out="${2:-/tmp/e2e-standalone-dual.yml}"
  cat >"${out}" <<EOF
# Generated by run-e2e-full-lab.sh — standalone dual-home targets only.
oracle_network_dataguard_enabled: true
oracle_network_interface: eth0
oracle_lab_host_map_mode: dataguard
oracle_db_manage_apply_instance_overrides_require_dataguard: false
