      archive: /duper/a01
      flashback: /duper/f01
      redo: /duper/r01
    dataguard: false
    archivelog: true
    flashback: false
    force_logging: true
    memory:
      sga_target: 1G
      pga_aggregate_target: 512M
    listener_vip: duperdb.domain.is
    listener_ip: 192.168.87.22
    listener_port: 1522
    service_name: duper_svc

  - name: fluff
    oracle_base: /fluff/app/oracle
    db_homes:
      - suffix: dbhome_1
        current: $([ "${current_home}" = "dbhome_1" ] && echo true || echo false)
      - suffix: dbhome_2
        current: $([ "${current_home}" = "dbhome_2" ] && echo true || echo false)
    gi_base: /grid
    gi_homes:
      - suffix: 19c/gi_home1
        current: true
      - suffix: 19c/gi_home2
        current: false
    dirs:
      data: /fluff/d01
      archive: /fluff/a01
      flashback: /fluff/f01
      redo: /fluff/r01
    dataguard: false
    archivelog: false
    flashback: false
    force_logging: false
    memory:
      sga_target: 1G
      pga_aggregate_target: 512M
    listener_vip: fluffdb.domain.is
    listener_ip: 192.168.87.23
    listener_port: 1523
    service_name: fluff_svc

